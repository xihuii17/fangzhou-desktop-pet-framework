// Original geometric example; no character artwork is copied.
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const root = path.resolve(__dirname, '..');
const shells = { standard: 'app', 'standard-music': 'variants/standard-music/app', growth: 'variants/growth/app', ai: 'variants/ai/app' };
function crc(bytes) {
  let c = 0xffffffff;
  for (const b of bytes) { c ^= b; for (let i = 0; i < 8; i++) c = (c >>> 1) ^ ((c & 1) ? 0xedb88320 : 0); }
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const t = Buffer.from(type), n = Buffer.alloc(4), check = Buffer.alloc(4);
  n.writeUInt32BE(data.length); check.writeUInt32BE(crc(Buffer.concat([t, data])));
  return Buffer.concat([n, t, data, check]);
}
function picture(wave) {
  const size = 256, rows = Buffer.alloc(size * (size * 4 + 1));
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
    const i = y * (size * 4 + 1) + 1 + x * 4;
    const body = (x - 128) ** 2 + (y - 140) ** 2 < 85 ** 2;
    const eye = ((x - 100) ** 2 + (y - 125) ** 2 < 7 ** 2) || ((x - 156) ** 2 + (y - 125) ** 2 < 7 ** 2);
    const hand = wave && (x - 220) ** 2 + (y - 80) ** 2 < 20 ** 2;
    const color = eye ? [25, 35, 55, 255] : body || hand ? [90, 185, 220, 255] : [0, 0, 0, 0];
    rows.set(color, i);
  }
  const header = Buffer.alloc(13); header.writeUInt32BE(size); header.writeUInt32BE(size, 4); header[8] = 8; header[9] = 6;
  return Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]), chunk('IHDR', header), chunk('IDAT', zlib.deflateSync(rows)), chunk('IEND', Buffer.alloc(0))]);
}
function prepare(variant) {
  if (!Object.hasOwn(shells, variant)) throw new Error('Unknown variant: ' + variant);
  const dest = path.join(root, '.stage', variant);
  const marker = path.join(dest, '.generated-example');
  if (fs.existsSync(dest)) {
    if (!fs.existsSync(marker)) throw new Error('Refusing to replace an unmarked staging directory: ' + dest);
    fs.rmSync(dest, { recursive: true, force: true });
  }
  fs.mkdirSync(dest, { recursive: true });
  fs.writeFileSync(marker, 'Generated by prepare-example.cjs\n');
  fs.cpSync(path.join(root, shells[variant]), dest, { recursive: true, filter: p => !p.split(path.sep).includes('node_modules') });
  const dir = path.join(dest, 'character');
  for (const sub of ['assets/gifs', 'assets/previews']) fs.mkdirSync(path.join(dir, sub), {recursive:true});
  const actions = ['idle', 'wave'].map(id => ({id, file:id+'.png', label:id, group:'base', modes:['quiet','daily','office'], auto:true, playMs:1600, lines:[]}));
  for (const a of actions) for (const sub of ['gifs', 'previews']) fs.writeFileSync(path.join(dir, 'assets', sub, a.file), picture(a.id === 'wave'));
  fs.writeFileSync(path.join(dir, 'assets/app-icon.png'), picture(false));
  fs.writeFileSync(path.join(dir, 'assets/tray.png'), picture(false));
  const metadata = {schemaVersion:1,id:'example',name:'小圆',productName:'Example Pet '+variant,packageName:'example-pet-'+variant,version:'0.1.0',appId:'org.example.pet.'+variant.replaceAll('-',''),defaultAction:'idle',greetingAction:'wave',greeting:'你好！',icon:'assets/app-icon.png',trayIcon:'assets/tray.png',buildVariant:variant,features:{aiChat:variant==='ai',growth:variant==='growth',qqLyrics:variant==='standard-music'},quickActions:[{label:'打招呼',actionId:'wave'}]};
  if (variant === 'ai') metadata.aiPersona = 'persona.json';
  metadata.features.lyrics = variant !== 'standard';
  const write = (file, value) => fs.writeFileSync(path.join(dir,file), JSON.stringify(value,null,2)+'\n');
  write('character.json',metadata); write('actions.json',actions);
  if (variant === 'ai') write('persona.json',{defaultProfile:{identity:'我是原创几何示例小圆。',personality:'友善、简洁。',relationship:'桌面伙伴。',speakingStyle:'自然简短。'},worldKnowledge:[],dialogueExamples:[],emotionActions:{neutral:['idle'],happy:['wave']}});
  const pkg = JSON.parse(fs.readFileSync(path.join(dest,'package.json'))); Object.assign(pkg,{name:metadata.packageName,productName:metadata.productName,license:'MIT',version:'0.1.0'});
  fs.writeFileSync(path.join(dest,'package.json'),JSON.stringify(pkg,null,2)+'\n');
  fs.writeFileSync(path.join(dest,'electron-builder.json'),JSON.stringify({appId:metadata.appId,productName:metadata.productName,electronVersion:'30.0.0',npmRebuild:false,asarUnpack:['**/*.ps1','**/*.scpt','**/*.wasm','now-playing.js','player-lyrics-macos.js','simplify-chinese.js'],directories:{output:path.join(root,'dist',variant)},files:['**/*','!electron-builder.json'],mac:{target:'dmg',identity:null},win:{target:'nsis'},publish:null},null,2));
  return dest;
}
module.exports = { prepare, shells };
if (require.main === module) for (const variant of process.argv.slice(2).length ? process.argv.slice(2) : Object.keys(shells)) console.log(prepare(variant));
